/**
 * A made-up session for demo mode: a Cobra Mk III leaves Kestrel Reach in Eravine,
 * jumps to Voss 214 and docks at an outpost with no large pads, a long approach and a
 * controlling faction in Lockdown. Every place, commander and faction here is
 * invented, and the field layout mirrors what the real journal writes.
 */
export interface DemoLine {
  /** When the line is "written", in milliseconds after the demo starts. */
  atMs: number;
  event: RawJournalEvent;
}

const T0 = Date.parse("2026-11-27T18:02:11Z");
const stamp = (atMs: number) => new Date(T0 + atMs).toISOString();

const line = (atMs: number, fields: { event: string } & Record<string, unknown>): DemoLine => ({
  atMs,
  event: { timestamp: stamp(atMs), ...fields },
});

